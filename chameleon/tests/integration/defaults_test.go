package integration

import (
	"context"
	"testing"

	"github.com/chameleon-db/chameleondb/chameleon/pkg/engine"
	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/stretchr/testify/require"
)

const defaultsSchema = `
entity Account {
    id: uuid primary default uuid(),
    token: uuid default uuid(),
    email: string unique,
    role: string default "user",
    active: bool default true,
    visits: int default 0,
    created_at: timestamp default now(),
}
`

// TestInsert_DatabaseDefaultsApplied verifies that fields omitted from an insert
// receive the default declared in the schema, including generated UUIDs.
func TestInsert_DatabaseDefaultsApplied(t *testing.T) {
	skipIfNoDocker(t)

	ctx := context.Background()
	config := testConfig()

	eng := engine.NewEngineForCLI()
	_, err := eng.LoadSchemaFromString(defaultsSchema)
	require.NoError(t, err)
	require.NoError(t, eng.Connect(ctx, config))
	defer eng.Close()

	dropAccounts := func() {
		conn, err := pgx.Connect(ctx, config.ConnectionString())
		if err != nil {
			t.Logf("Warning: failed to connect for cleanup: %v", err)
			return
		}
		defer conn.Close(ctx)
		_, _ = conn.Exec(ctx, "DROP TABLE IF EXISTS accounts CASCADE")
	}
	dropAccounts()
	defer dropAccounts()

	runMigration(t, eng, ctx)

	first, err := eng.Insert("Account").
		Set("email", "first@mail.com").
		Execute(ctx)
	require.NoError(t, err)

	second, err := eng.Insert("Account").
		Set("email", "second@mail.com").
		Execute(ctx)
	require.NoError(t, err)

	// Primary key generated by the database, different for each row.
	firstID := uuidString(t, first.Record["id"])
	secondID := uuidString(t, second.Record["id"])
	require.NotEqual(t, firstID, secondID)

	// Another uuid field also gets its own value.
	require.NotEqual(t, firstID, uuidString(t, first.Record["token"]))

	// Literal and function defaults.
	require.Equal(t, "user", first.Record["role"])
	require.Equal(t, true, first.Record["active"])
	require.EqualValues(t, 0, first.Record["visits"])
	require.NotNil(t, first.Record["created_at"])

	// An explicit value wins over the default.
	explicit := uuid.New().String()
	third, err := eng.Insert("Account").
		Set("id", explicit).
		Set("email", "third@mail.com").
		Set("role", "admin").
		Execute(ctx)
	require.NoError(t, err)
	require.Equal(t, explicit, uuidString(t, third.Record["id"]))
	require.Equal(t, "admin", third.Record["role"])
}

// uuidString normalizes the value pgx returns for a UUID column ([16]byte or string).
func uuidString(t *testing.T, v interface{}) string {
	t.Helper()

	switch value := v.(type) {
	case string:
		return value
	case [16]byte:
		parsed, err := uuid.FromBytes(value[:])
		require.NoError(t, err)
		return parsed.String()
	default:
		t.Fatalf("unexpected uuid value type %T", v)
		return ""
	}
}
