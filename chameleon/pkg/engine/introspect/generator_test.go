func TestToEntityName(t *testing.T) {
	tests := []struct {
		name      string
		tableName string
		want      string
	}{
		{name: "regular plural", tableName: "users", want: "User"},
		{name: "snake case plural", tableName: "user_posts", want: "UserPost"},
		{name: "irregular plural", tableName: "people", want: "Person"},
		{name: "irregular plural in last segment", tableName: "user_people", want: "UserPerson"},
		{name: "irregular ending with es", tableName: "statuses", want: "Status"},
		{name: "already singular", tableName: "profile", want: "Profile"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := toEntityName(tt.tableName)
			if got != tt.want {
				t.Fatalf("toEntityName(%q) = %q, want %q", tt.tableName, got, tt.want)
			}
		})
	}
}

func TestMapColumnType(t *testing.T) {
	tests := []struct {
		name    string
		sqlType string
		want    string
	}{
		{name: "uuid", sqlType: "uuid", want: "uuid"},
		{name: "varchar", sqlType: "varchar", want: "string"},
		{name: "integer", sqlType: "integer", want: "int"},
		{name: "numeric", sqlType: "numeric", want: "decimal"},
		{name: "double precision", sqlType: "double precision", want: "float"},
		{name: "boolean", sqlType: "boolean", want: "bool"},
		{name: "timestamp with tz", sqlType: "timestamp with time zone", want: "timestamp"},
		{name: "timestamp without tz", sqlType: "timestamp without time zone", want: "timestamp"},
		{name: "character", sqlType: "character", want: "string"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, mapped := mapColumnType(tt.sqlType)
			if got != tt.want {
				t.Fatalf("mapColumnType(%q) = %q, want %q", tt.sqlType, got, tt.want)
			}
			if !mapped {
				t.Fatalf("mapColumnType(%q) reported no mapping", tt.sqlType)
			}
		})
	}
}

func TestMapColumnType_UnknownTypeIsFlagged(t *testing.T) {
	for _, sqlType := range []string{"jsonb", "ARRAY", "USER-DEFINED", "bytea", "time without time zone", "xml"} {
		got, mapped := mapColumnType(sqlType)
		if got != "string" || mapped {
			t.Fatalf("mapColumnType(%q) = (%q, %v), want (\"string\", false)", sqlType, got, mapped)
		}
	}
}

func TestGenerateChameleonSchema_WarnsOnUnmappedType(t *testing.T) {
	tables := []TableInfo{
		{
			Name: "events",
			Columns: []ColumnInfo{
				{Name: "id", Type: "uuid", PrimaryKey: true},
				{Name: "payload", Type: "jsonb"},
				{Name: "created_at", Type: "timestamp without time zone"},
			},
		},
	}

	schema, err := GenerateChameleonSchema(tables)
	if err != nil {
		t.Fatalf("GenerateChameleonSchema failed: %v", err)
	}

	if !strings.Contains(schema, `payload: string, // WARNING: PostgreSQL type "jsonb" has no ChameleonDB equivalent`) {
		t.Fatalf("expected a warning for the jsonb column, got:\n%s", schema)
	}
	if !strings.Contains(schema, "created_at: timestamp,\n") {
		t.Fatalf("expected created_at to map to timestamp without a warning, got:\n%s", schema)
	}
	if strings.Count(schema, "WARNING") != 1 {
		t.Fatalf("expected exactly one warning, got:\n%s", schema)
	}
}

func TestGenerateChameleonSchema(t *testing.T) {
	tables := []TableInfo{
		{
			Name: "users",
			Columns: []ColumnInfo{
				{Name: "id", Type: "uuid", PrimaryKey: true},
				{Name: "email", Type: "varchar", Unique: true},
				{Name: "name", Type: "text", Nullable: true},
			},
		},
		{
			Name: "posts",
			Columns: []ColumnInfo{
				{Name: "id", Type: "uuid", PrimaryKey: true},
				{
					Name: "author_id",
					Type: "uuid",
					ForeignKey: &ForeignKeyInfo{
						ReferencedTable:  "users",
						ReferencedColumn: "id",
					},
				},
			},
		},
	}

	schema, err := GenerateChameleonSchema(tables)
	if err != nil {
		t.Fatalf("GenerateChameleonSchema() error = %v", err)
	}

	checks := []string{
		"// Auto-generated by: chameleon introspect",
		"entity User {",
		"id: uuid primary,",
		"email: string unique,",
		"name: string nullable,",
		"entity Post {",
		"author_id: uuid,",
		"// Foreign key relationships",
		"//   Post.author_id: [User] via author_id,",
	}

	for _, check := range checks {
		if !strings.Contains(schema, check) {
			t.Fatalf("expected generated schema to contain %q\nGot:\n%s", check, schema)
		}
	}
}
